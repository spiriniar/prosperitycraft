function wootmob(mob,spirits){
    WootStartupEvents.registerFactoryMob(`minecraft:${mob}`, event => {
        event.registerDropsModifier(properties => {
            let looting = properties.getEnchantmentLevel("looting");
            let itemDrops=[];
            spirits.forEach(spirit=>{
                itemDrops.push({item:`malum:${spirit.split('*')[1]}_spirit`,count:spirit.split('*')[0]*looting})
            })
            properties.setItemDrops(itemDrops);
        })
    })
}
