StartupEvents.registry('block', event => {
    event.create('runewood_quarry').displayName('Runewood Quarry')
        .fullBlock(true)
        .material("wood")
        .soundType("wood")
        .hardness(4)
        .resistance(4)
        .requiresTool(true)
        .tagBlock('minecraft:mineable/axe')
        .tagBlock('minecraft:needs_iron_tool')
    event.create('cobalt_block').displayName('Cobalt Block')
        .fullBlock(true)
        .material("metal")
        .soundType("metal")
        .hardness(9)
        .resistance(10)
        .requiresTool(true)
        .tagBlock('minecraft:mineable/pickaxe')
        .tagBlock('minecraft:needs_diamond_tool')
        .tag('forge:storage_blocks')
        .tag('forge:storage_blocks/cobalt')
})